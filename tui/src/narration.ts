/**
 * The demo script, generated from the scenario and the derived figures, so
 * that the narration cannot drift from the panels (Phase 4 of the critique).
 * `node src/main.ts --narration > docs/demo-script.md` writes it; a test
 * checks that the committed file equals the generated text.
 *
 * Rules: every number in the script is `format(derived)`; the script states
 * what happens and what the panels show; it has no editorial closer.
 */
import type { Inputs } from "./data.ts"
import { type Derived, type Figures, format, input } from "./derive.ts"
import { eventText, type Scenario } from "./scenario.ts"

const mmss = (s: number): string => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, "0")}`

interface Cue {
  readonly at: number // recording seconds
  readonly action: string
  readonly say: string
}

/** Seconds of idle screen before SPACE is pressed in the recording. */
const leadIn = (inp: Inputs): number => inp.run.autoTriggerIdleS

export const narration = (inp: Inputs, fig: Figures, sc: Scenario): string => {
  const tl = sc.timeline
  const c = fig.cost
  const f = (d: Derived) => format(d)
  const clock = (t: number) => format(sc.clock(t))
  const lead = leadIn(inp)
  const crash = tl.crash
  const approveAt = tl.review + tl.autoApproveDelay
  const lease = input("run.leaseS", inp.run.leaseS, "s")
  const renew = input("run.renewS", inp.run.renewS, "s")
  const agents = inp.run.agents.map((a) => a.id).join(", ")
  const takeoverWrite = crash === null ? undefined : tl.writes.find((w) => w.kind === "takeover")

  const cold: Cue[] = [
    { at: 0, action: "Idle screen (`node src/main.ts --autoplay`).", say: `${inp.project.name}: ${agents} share one monorepo build; R2 conditional writes are the only coordination.` },
    { at: lead, action: "The run starts (autoplay presses SPACE).", say: `Each agent forks trunk and takes a lease on its operation with If-None-Match: *. Holders renew every ${f(renew)}; a lease lasts ${f(lease)}.` },
    ...(crash === null
      ? []
      : [
          { at: lead + crash.at, action: "Panel 2: the renewal of the crashed holder is missing.", say: `${crash.agent} misses its renewal of ${crash.op}, due at ${clock(crash.renewalDue)}.` },
          {
            at: lead + crash.expiry,
            action: "Event stream: LEASE, then the takeover.",
            say: `${f(lease)} after its last write (${clock(crash.lastWrite)}) the lease expires; ${crash.taker} takes over with If-Match on ${takeoverWrite?.ifMatch ?? "the last ETag"}.`
          },
          { at: lead + crash.takeoverDone, action: "Event stream: cache HIT.", say: `${crash.taker} reuses the published manifest: ${f(fig.cache.blobCount)}, ${f(fig.cache.stored)}, verified.` }
        ]),
    { at: lead + approveAt, action: "Autoplay approves the PR; COST line.", say: `This run cost ${f(c.cobuildsPerRun)}, against ${f(c.ghaPerRun)} on GitHub Actions.` },
    {
      at: lead + approveAt + tl.autoApproveDelay,
      action: "Press 5 (cost panel).",
      say: `At ${f(c.runsPerMonth)}: ${f(c.cobuildsMonthly)} against ${f(c.ghaMonthly)} on standard runners, ${f(c.savingsPct)} less.`
    }
  ]
  const coldEnd = cold[cold.length - 1]!.at

  const full = sc.script.map((e) => `| ${mmss(lead + e.t)} | ${clock(e.t)} | ${e.kind} | ${eventText(e).replace(/\|/g, "\\|")} |`)

  const quoted: ReadonlyArray<readonly [string, Derived]> = [
    ["lease", lease],
    ["renewal interval", renew],
    ["blobs", fig.cache.blobCount],
    ["entry size", fig.cache.stored],
    ["Cobuilds per run", c.cobuildsPerRun],
    ["GHA per run", c.ghaPerRun],
    ["runs per month", c.runsPerMonth],
    ["Cobuilds monthly", c.cobuildsMonthly],
    ["GHA monthly (standard)", c.ghaMonthly],
    ["monthly savings", c.savingsPct]
  ]

  return [
    "# Demo script (generated)",
    "",
    "Generated by `node src/main.ts --narration` from `tui/inputs.json` (do not edit by hand;",
    "`test/narration.test.ts` fails if this file differs from the generated text).",
    "Times are recording times: the run starts after the autoplay lead-in.",
    "",
    `## Cold open (${mmss(coldEnd)})`,
    "",
    "| Time | Action | Say |",
    "|---|---|---|",
    ...cold.map((q) => `| ${mmss(q.at)} | ${q.action} | ${q.say} |`),
    "",
    "## Full walkthrough",
    "",
    "Let the run play (`--autoplay`), then tour the panels with `1`–`5` and `e`, and open the data notes with `n`.",
    "",
    "| Time | Clock | Kind | Event |",
    "|---|---|---|---|",
    ...full,
    `| ${mmss(lead + approveAt)} | ${clock(approveAt)} | MERGE | (autoplay approves; on reject the stream shows REJECT) |`,
    "",
    "Panel tour after the merge:",
    "",
    "1. `1` forks: each agent's fork, token TTL, branch, commit and diff; the taker's second fork.",
    "2. `2` locks: per-key ETags (`<op>.v<n>`), expiry countdowns, the takeover's predecessor.",
    "3. `3` cache: blobs, manifest, hit rate, dedup; the entry size (MB) next to the retained storage of the cost model (GB-month).",
    "4. `4` Lean metrics: algorithm table, phase totals (one total per variant in both tables), scaling with the Amdahl column.",
    "5. `5` cost: bars normalised to the largest cost, itemised monthly total, per-run table.",
    "6. `n` notes: each figure the brief states, the derived value, and the decision taken.",
    "",
    "## Figures quoted",
    "",
    "| Figure | Value | Formula |",
    "|---|---|---|",
    ...quoted.map(([name, d]) => `| ${name} | ${format(d)} | ${d.formula} |`),
    ""
  ].join("\n")
}
